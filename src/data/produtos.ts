export function produtoPorSlug(slug: string): Produto | undefined {
  return produtos.find((p) => p.slug === slug);
}

export function produtoPorId(id: string): Produto | undefined {
  return produtos.find((p) => p.id === id);
}

export function categoriaPorSlug(slug: string): Categoria | undefined {
  return categorias.find((c) => c.slug === slug);
}

export function produtosDaCategoria(slug: string): Produto[] {
  return produtos.filter((p) => p.categoria === slug);
}

export function relacionados(produto: Produto, quantidade = 4): Produto[] {
  const mesmaCategoria = produtos.filter((p) => p.categoria === produto.categoria && p.id !== produto.id);
  const outros = produtos.filter((p) => p.categoria !== produto.categoria && p.id !== produto.id);
  return [...mesmaCategoria, ...outros].slice(0, quantidade);
}

export function formatarPreco(valor: number): string {
  return valor.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
}

/** Parcelamento sugerido: até 3x sem juros a partir de R$ 150. */
export function parcelamento(valor: number): { vezes: number; valor: number } {
  const vezes = valor >= 150 ? 3 : valor >= 90 ? 2 : 1;
  return { vezes, valor: valor / vezes };
}
